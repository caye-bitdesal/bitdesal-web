import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import {
	shouldRedirectLangQuery,
	supportedLanguages,
	targetPathForLangQuery,
} from './lang-redirect-core.mjs';

const SLUGS_FOR_LANG_RULES = [
	'aviso-legal',
	'legal-notice',
	'oikeudellinen-ilmoitus',
	'privacidad',
	'privacy',
	'tietosuoja',
	'casos-y-precios',
	'work-and-pricing',
	'referenssit-ja-hinnat',
	'methodology',
	'contacto',
	'consultoria-ia',
	'consultoria-software',
	'nosotros',
	'blog',
	'caye',
	'ramiro',
];

function pathVariants(slug) {
	if (!slug) return ['/'];
	return [`/${slug}`, `/en/${slug}`, `/fi/${slug}`];
}

function apachePathPattern(pathname) {
	const clean = pathname.replace(/\/$/, '') || '/';
	if (clean === '/') return '^/?$';
	const segments = clean.replace(/^\//, '').split('/');
	return `^${segments.join('/')}/?$`;
}

function langQueryRules() {
	const rules = [];
	const seen = new Set();

	for (const slug of SLUGS_FOR_LANG_RULES) {
		for (const pathname of pathVariants(slug)) {
			for (const lang of supportedLanguages) {
				if (!shouldRedirectLangQuery(pathname, lang)) continue;
				const target = targetPathForLangQuery(pathname, lang);
				const key = `${lang}|${pathname}|${target}`;
				if (seen.has(key)) continue;
				seen.add(key);
				const pattern = apachePathPattern(pathname);
				rules.push(
					`RewriteCond %{QUERY_STRING} (^|&)lang=${lang}(&|$) [NC]`,
					`RewriteRule ${pattern} ${target} [R=301,L,QSD]`,
				);
			}
		}
	}

	for (const lang of supportedLanguages) {
		if (!shouldRedirectLangQuery('/', lang)) continue;
		const target = targetPathForLangQuery('/', lang);
		rules.push(
			`RewriteCond %{QUERY_STRING} (^|&)lang=${lang}(&|$) [NC]`,
			`RewriteRule ^/?$ ${target} [R=301,L,QSD]`,
		);
	}

	return rules;
}

if (targetPathForLangQuery('/methodology/', 'fi') !== '/fi/consultoria-software/') {
	throw new Error('methodology → fi consultoria-software redirect mismatch');
}

const body = `# Generated by scripts/write-htaccess.mjs — do not edit by hand.
<IfModule mod_rewrite.c>
RewriteEngine On

# ?lang= (must run before bare /methodology/ redirect)
${langQueryRules().join('\n\n')}

# Legacy WordPress/demo URLs (PHP fallback on host)
RewriteRule ^post-1/?$ /blog/ [R=301,L]
RewriteRule ^blog-2/?$ /blog/ [R=301,L]

# 301 instead of Astro meta-refresh redirect pages (no ?lang=)
RewriteCond %{QUERY_STRING} !(^|&)lang= [NC]
RewriteRule ^methodology/?$ /consultoria-software/ [R=301,L]
</IfModule>
`;

const outPath = fileURLToPath(new URL('../public/.htaccess', import.meta.url));
writeFileSync(outPath, body);
console.log(`Wrote ${outPath}`);
